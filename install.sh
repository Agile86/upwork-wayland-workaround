#!/bin/bash
# install.sh - Install desktop launcher for Upwork Wayland Bridge

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DESKTOP_DIR="${HOME}/.local/share/applications"
# Distinct file name and display name so it is not confused with (or shadowed
# by) the system /usr/share/applications/upwork.desktop entry.
DESKTOP_FILE="${DESKTOP_DIR}/upwork-fixed.desktop"
LEGACY_DESKTOP_FILE="${DESKTOP_DIR}/upwork.desktop"

# Ensure scripts are executable
chmod +x "$SCRIPT_DIR/screenshot.py" "$SCRIPT_DIR/upwork-launcher.sh"

# Find icon from system desktop file, fall back to theme name
ICON="upwork"
SYSTEM_DESKTOP="/usr/share/applications/upwork.desktop"
if [ -f "$SYSTEM_DESKTOP" ]; then
    ORIG_ICON=$(grep -m1 "^Icon=" "$SYSTEM_DESKTOP" | cut -d= -f2-)
    [ -n "$ORIG_ICON" ] && ICON="$ORIG_ICON"
fi

mkdir -p "$DESKTOP_DIR"

# Don't silently clobber a desktop file we didn't create
MARKER="# Generated by upwork-wayland-workaround install.sh"

# Earlier versions wrote ~/.local/share/applications/upwork.desktop, which
# overrode the system entry. Remove it if we generated it.
if [ -f "$LEGACY_DESKTOP_FILE" ] && grep -qxF "$MARKER" "$LEGACY_DESKTOP_FILE"; then
    rm -- "$LEGACY_DESKTOP_FILE"
    echo "Removed old generated launcher: $LEGACY_DESKTOP_FILE"
fi

if [ -f "$DESKTOP_FILE" ] && ! grep -qxF "$MARKER" "$DESKTOP_FILE"; then
    BACKUP="${DESKTOP_FILE}.bak"
    [ -e "$BACKUP" ] || cp -- "$DESKTOP_FILE" "$BACKUP"
    echo "Existing $DESKTOP_FILE backed up to $BACKUP"
fi

# Quote the Exec path per the Desktop Entry spec so spaces/special chars work:
# inside double quotes, escape \ " ` $ with a backslash, and % as %%.
EXEC_PATH="$SCRIPT_DIR/upwork-launcher.sh"
EXEC_PATH="${EXEC_PATH//\\/\\\\\\\\}"
EXEC_PATH="${EXEC_PATH//\"/\\\\\"}"
EXEC_PATH="${EXEC_PATH//\`/\\\\\`}"
EXEC_PATH="${EXEC_PATH//\$/\\\\\$}"
EXEC_PATH="${EXEC_PATH//%/%%}"

cat > "$DESKTOP_FILE" << EOF
$MARKER
[Desktop Entry]
Name=Upwork - fixed
Comment=Upwork Desktop Application (Wayland workaround launcher)
Exec="${EXEC_PATH}" %U
Icon=${ICON}
Terminal=false
Type=Application
StartupWMClass=Upwork
MimeType=x-scheme-handler/upwork;
Categories=Utility;
EOF

# Update desktop database so the DE picks up the change
if command -v update-desktop-database &>/dev/null; then
    update-desktop-database "$DESKTOP_DIR" 2>/dev/null
fi

echo "Desktop launcher installed: $DESKTOP_FILE"
